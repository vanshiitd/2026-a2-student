# quick profile of corpus / queries / qrels (and pools if given), dumps markdown
# usage: python -m experiments.profile_data --data data/full --out ../notes/corpus_profile.md [--pool p.jsonl ...]
import argparse
import os
from collections import Counter

from harness.candidates_io import read_candidates
from harness.trec_io import read_qrels, read_queries
from submission.corpus_utils import load_corpus
from submission.lm_utils import tokenize


def pct(sorted_vals, ps=(0, 5, 25, 50, 75, 95, 99, 100)):
    n = len(sorted_vals)
    return " · ".join(f"p{p}={sorted_vals[min(n - 1, int(p / 100 * n))]}" for p in ps)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--pool", action="append", default=[])
    args = ap.parse_args()

    corpus = load_corpus(os.path.join(args.data, "corpus.jsonl"))
    queries = read_queries(os.path.join(args.data, "queries_dev.tsv"))
    qrels = read_qrels(os.path.join(args.data, "qrels_dev.txt"))

    df = Counter()
    lens = []
    for _, text in corpus:
        toks = tokenize(text)
        lens.append(len(toks))
        df.update(set(toks))
    n_docs = len(corpus)
    lens_sorted = sorted(lens)

    L = []
    L.append("# Data profile\n")
    L.append(f"_Generated by `experiments/profile_data.py` from `{args.data}` (starter tokenizer, no stemming/stopwords)._\n")
    L.append("## Corpus\n")
    L.append("| Metric | Value |\n|---|---|")
    L.append(f"| Documents | {n_docs:,} |")
    L.append(f"| Total tokens | {sum(lens):,} |")
    L.append(f"| Avg doc length | {sum(lens) / n_docs:.1f} |")
    L.append(f"| Doc length pctl | {pct(lens_sorted)} |")
    L.append(f"| Empty docs | {sum(1 for x in lens if x == 0)} |")
    L.append(f"| Vocab size | {len(df):,} |\n")

    # queries
    qlens = sorted(len(tokenize(t)) for _, t in queries)
    L.append("## Queries\n")
    L.append(f"{len(queries)} queries, token length {pct(qlens)}, avg {sum(qlens) / len(qlens):.2f}\n")
    # how much of the query is junk (very high df words)
    q_df = Counter()
    for _, t in queries:
        for w in tokenize(t):
            q_df[w] += 1
    L.append("Most frequent query terms (with corpus df fraction):\n")
    L.append("| term | #queries | df/N |\n|---|---|---|")
    for w, c in q_df.most_common(20):
        L.append(f"| {w} | {c} | {df[w] / n_docs:.3f} |")
    L.append("")

    # qrels
    labels = Counter(r for q in qrels.values() for r in q.values())
    rel_per_q = sorted(sum(1 for r in q.values() if r > 0) for q in qrels.values())
    L.append("## Qrels\n")
    L.append(f"Labels: {dict(sorted(labels.items()))}; judged/query avg {sum(len(q) for q in qrels.values()) / len(qrels):.0f}; "
             f"relevant(>0)/query {pct(rel_per_q, (0, 25, 50, 75, 100))}\n")

    # pools, if any
    for p in args.pool:
        cands = read_candidates(p)
        sizes, rec, judged, prec10 = [], [], [], []
        for qid, lst in cands.items():
            ids = [d for d, _ in lst]
            qr = qrels.get(qid, {})
            nrel = sum(1 for r in qr.values() if r > 0)
            sizes.append(len(ids))
            rec.append(sum(1 for d in ids if qr.get(d, 0) > 0) / max(1, nrel))
            judged.append(sum(1 for d in ids if d in qr) / max(1, len(ids)))
            prec10.append(sum(1 for d in ids[:10] if qr.get(d, 0) > 0) / 10)
        n = len(cands)
        L.append(f"## Pool `{os.path.basename(p)}`\n")
        L.append(f"{n} queries, size min/max {min(sizes)}/{max(sizes)}, recall avg {sum(rec) / n:.3f}, "
                 f"judged fraction {sum(judged) / n:.3f}, P@10 in pool order {sum(prec10) / n:.3f}\n")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
